"""
Fetch the AWS list prices the cost model uses and write them to rates.py.

Source: the AWS Price List API (pricing:GetProducts), AWS's published list prices, for
Asia Pacific (Mumbai) = ap-south-1. This is not the Pricing Calculator web page itself;
the calculator's output should match, which is why docs/cost-model.md lists the rates
to confirm there.
Read-only: it creates no AWS resources. Needs AWS credentials that allow
pricing:GetProducts and boto3 (pip install boto3).

Every rate is written to rates.py as a labelled constant with its SKU, usage type,
the date AWS published that price record, and the date this script retrieved it.
The raw API record for each rate is saved under rates_raw/ so the numbers can be
checked against what AWS returned. Nothing here is typed from memory.

Usage: python cost/fetch_rates.py
"""
import json
from datetime import datetime, timezone
from pathlib import Path

import boto3

HERE = Path(__file__).resolve().parent
RAW = HERE / "rates_raw"
LOCATION = "Asia Pacific (Mumbai)"

client = boto3.client("pricing", region_name="us-east-1")  # the API's endpoint region


def products(service, **filters):
    flt = [{"Type": "TERM_MATCH", "Field": k, "Value": v} for k, v in filters.items()]
    found, token = [], None
    while True:
        kwargs = dict(ServiceCode=service, Filters=flt, FormatVersion="aws_v1", MaxResults=100)
        if token:
            kwargs["NextToken"] = token
        page = client.get_products(**kwargs)
        found += [json.loads(p) for p in page["PriceList"]]
        token = page.get("NextToken")
        if not token:
            return found


def one(service, usagetype, **filters):
    matches = [p for p in products(service, **filters)
               if p["product"]["attributes"].get("usagetype") == usagetype]
    if len(matches) != 1:
        raise SystemExit(f"expected exactly one {service} product with usagetype {usagetype}, got {len(matches)}")
    return matches[0]


def dimensions(product):
    """On-demand price tiers as (begin, end, usd, unit, description), by begin."""
    out = []
    for term in product["terms"]["OnDemand"].values():
        for d in term["priceDimensions"].values():
            end = None if d["endRange"] == "Inf" else float(d["endRange"])
            out.append((float(d["beginRange"]), end, float(d["pricePerUnit"]["USD"]),
                        d["unit"], d["description"]))
    return sorted(out)


# name, service, usagetype, extra filters, tiered?
SPECS = [
    ("EC2_T3_MICRO_USD_PER_HOUR", "AmazonEC2", "APS3-BoxUsage:t3.micro",
     dict(location=LOCATION, instanceType="t3.micro", operatingSystem="Linux", tenancy="Shared",
          preInstalledSw="NA", capacitystatus="Used"), False),
    ("EBS_GP3_USD_PER_GB_MONTH", "AmazonEC2", "APS3-EBS:VolumeUsage.gp3",
     dict(location=LOCATION, productFamily="Storage", volumeApiName="gp3"), False),
    ("ALB_USD_PER_HOUR", "AWSELB", "APS3-LoadBalancerUsage",
     dict(location=LOCATION, productFamily="Load Balancer-Application"), False),
    ("ALB_LCU_USD_PER_LCU_HOUR", "AWSELB", "APS3-LCUUsage",
     dict(location=LOCATION, productFamily="Load Balancer-Application"), False),
    ("PUBLIC_IPV4_IN_USE_USD_PER_HOUR", "AmazonVPC", "APS3-PublicIPv4:InUseAddress",
     dict(location=LOCATION), False),
    ("DDB_READ_USD_PER_REQUEST_UNIT", "AmazonDynamoDB", "APS3-ReadRequestUnits",
     dict(location=LOCATION), False),
    ("DDB_WRITE_USD_PER_REQUEST_UNIT", "AmazonDynamoDB", "APS3-WriteRequestUnits",
     dict(location=LOCATION), False),
    ("DDB_STORAGE_TIERS_USD_PER_GB_MONTH", "AmazonDynamoDB", "APS3-TimedStorage-ByteHrs",
     dict(location=LOCATION), True),
    ("S3_STANDARD_STORAGE_TIERS_USD_PER_GB_MONTH", "AmazonS3", "APS3-TimedStorage-ByteHrs",
     dict(location=LOCATION), True),
    ("S3_PUT_COPY_POST_LIST_USD_PER_REQUEST", "AmazonS3", "APS3-Requests-Tier1",
     dict(location=LOCATION), False),
    ("S3_GET_USD_PER_REQUEST", "AmazonS3", "APS3-Requests-Tier2",
     dict(location=LOCATION), False),
    ("DATA_TRANSFER_OUT_TIERS_USD_PER_GB", "AWSDataTransfer", "APS3-DataTransfer-Out-Bytes",
     dict(fromLocation=LOCATION, toLocation="External"), True),
    ("CLOUDWATCH_STANDARD_ALARM_USD_PER_MONTH", "AmazonCloudWatch", "APS3-CW:AlarmMonitorUsage",
     dict(location=LOCATION), False),
]


def main():
    RAW.mkdir(exist_ok=True)
    retrieved = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    lines = [
        '"""',
        "AWS list prices, Asia Pacific (Mumbai) / ap-south-1, USD.",
        "",
        "GENERATED by cost/fetch_rates.py. Do not edit by hand: re-run the script.",
        "Source: AWS Price List API (pricing:GetProducts, aws_v1), AWS's published list prices.",
        "Not the Pricing Calculator web page itself; confirm against it (see docs/cost-model.md).",
        f"Retrieved: {retrieved} (UTC date)",
        "Free tiers, credits, discounts and savings plans are NOT applied: list price only.",
        '"""',
        "",
        f'RETRIEVED = "{retrieved}"',
        'SOURCE = "AWS Price List API (pricing:GetProducts), Asia Pacific (Mumbai)"',
        "",
        "# name -> metadata, for printing and for the writeup's rate table",
        "RATE_INFO = {}",
        "",
    ]
    for name, service, usagetype, flt, tiered in SPECS:
        product = one(service, usagetype, **flt)
        (RAW / f"{name}.json").write_text(json.dumps(product, indent=2))
        dims = dimensions(product)
        sku = product["product"]["sku"]
        published = product.get("publicationDate", "unknown")
        label = dims[0][4] if not tiered else dims[0][4].split(" - ")[0]
        lines.append(f"# {service} | usagetype {usagetype} | sku {sku} | AWS published {published}")
        for begin, end, usd, unit, desc in dims:
            lines.append(f"#   {unit}: {begin:g} to {'inf' if end is None else format(end, 'g')} -> ${usd:g} | {desc}")
        if tiered:
            tiers = ", ".join(f"({b:g}, {'None' if e is None else format(e, 'g')}, {u!r})" for b, e, u, _, _ in dims)
            lines.append(f"{name} = [{tiers}]  # (from, to, usd); to=None means no upper limit; units: {dims[0][3]}")
        else:
            lines.append(f"{name} = {dims[0][2]!r}  # usd per {dims[0][3]}")
        lines.append(f'RATE_INFO["{name}"] = dict(service="{service}", usagetype="{usagetype}", sku="{sku}", '
                     f'published="{published}", unit="{dims[0][3]}")')
        lines.append("")
        print(f"{name}: sku {sku}, published {published}, " + "; ".join(f"{d[2]:g}/{d[3]}" for d in dims))
    (HERE / "rates.py").write_text("\n".join(lines) + "\n")
    print(f"wrote {HERE / 'rates.py'} and {len(SPECS)} raw records in {RAW}")


if __name__ == "__main__":
    main()
