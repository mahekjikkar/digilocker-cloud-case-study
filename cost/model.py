# ---------------------------------------------------------------------------
# 1. Unit definitions published by AWS (not prices). Retrieved 2026-10-31.
# ---------------------------------------------------------------------------
# ALB capacity unit (LCU), billed on the highest of four dimensions, averaged over the hour.
#   https://aws.amazon.com/elasticloadbalancing/pricing/
LCU_NEW_CONNECTIONS_PER_SEC = 25
LCU_ACTIVE_CONNECTIONS_PER_MIN = 3000
LCU_PROCESSED_GB_PER_HOUR = 1          # EC2 targets
# Rule evaluations are ignored: the first 10 rules are free and we use one (default) rule.
# DynamoDB read unit: one eventually consistent read of an item up to 4 KB = 0.5 read units.
#   https://docs.aws.amazon.com/amazondynamodb/latest/developerguide/read-write-operations.html
DDB_EVENTUALLY_CONSISTENT_READ_UNITS_PER_4KB = 0.5
DDB_READ_UNIT_BYTES = 4096
DDB_WRITE_UNIT_BYTES = 1024            # one write unit per 1 KB of item
# DynamoDB bills storage as item size plus 100 bytes of overhead per item.
#   https://docs.aws.amazon.com/amazondynamodb/latest/developerguide/CapacityUnitCalculations.html
DDB_STORAGE_OVERHEAD_BYTES = 100
GIB = 2 ** 30                          # AWS bills storage and transfer "GB" as 2^30 bytes

# ---------------------------------------------------------------------------
# 2. ASSUMPTIONS (not measured, not in the Price List). Change them here.
# ---------------------------------------------------------------------------
HOURS_PER_MONTH = 730                  # 365 x 24 / 12
DOCUMENTS = 941 * 10 ** 7              # 941 crore documents (Week 2 report s.5; source not named there)
DOC_SIZE_BYTES = 100 * 1024            # ASSUMED average issued document (signed XML + PDF): 100 KiB
POINTER_ATTR_BYTES = 100               # ASSUMED attribute bytes per pointer (measured seed average is below)
ALB_PUBLIC_IPV4_ADDRESSES = 2          # ASSUMED: one per zone for an internet-facing ALB in 2 zones
CLOUDWATCH_ALARMS = 2                  # ASSUMED: the high/low alarm pair of one target-tracking policy
CLOUDWATCH_ALARMS_ARE_BILLED = True    # ASSUMED (conservative); not stated in the Price List
ROOT_VOLUME_GB = 8                     # MEASURED: AMI root volume (ec2 describe-images, ami-0ee5a319d86dca0ab)
POINTER_CACHE_TTL_SECONDS = 60         # from app/store.py (METADATA_CACHE_TTL default)
TESTED_DISTINCT_POINTERS = len(SEED)   # 4 pointers existed in the tested table
SENSITIVITY_DOC_SIZES_KIB = [25, 100, 500]
SENSITIVITY_POINTER_ATTR_BYTES = [50, 100, 200]

