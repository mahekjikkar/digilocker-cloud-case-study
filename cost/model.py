def tiered(tiers, quantity):
    """Cost of `quantity` units across (from, to, usd-per-unit) tiers; to=None is open-ended."""
    cost = 0.0
    for begin, end, usd in tiers:
        if quantity <= begin:
            break
        top = quantity if end is None else min(quantity, end)
        cost += (top - begin) * usd
    return cost


def seed_attribute_bytes():
    """Average attribute bytes (names + values) of the pointer records the registry stored."""
    sizes = []
    for uri, (issuer, doc_id, doc_type) in SEED.items():
        row = {"uri": uri, "issuer": issuer, "doc_id": doc_id, "doc_type": doc_type}
        sizes.append(sum(len(k.encode()) + len(v.encode()) for k, v in row.items()))
    return sum(sizes) / len(sizes)


def ddb_read_units(item_bytes):
    return DDB_EVENTUALLY_CONSISTENT_READ_UNITS_PER_4KB * math.ceil(item_bytes / DDB_READ_UNIT_BYTES)


def ddb_write_units(item_bytes):
    return math.ceil(item_bytes / DDB_WRITE_UNIT_BYTES)


def pointer_item_bytes(attr_bytes=POINTER_ATTR_BYTES):
    return attr_bytes + DDB_STORAGE_OVERHEAD_BYTES


def pointer_storage_month(items, attr_bytes=POINTER_ATTR_BYTES):
    gib = items * pointer_item_bytes(attr_bytes) / GIB
    return tiered(R.DDB_STORAGE_TIERS_USD_PER_GB_MONTH, gib), gib


PROFILES = {
    "as_tested": "As tested: the mock payload (about 0.4 KB), the 4 pointers that existed (cache hits)",
    "national_scale": "National scale: assumed 100 KiB documents, every lookup a cache miss, 941 crore pointers stored",
}


def hourly_cost(m, profile):
    """USD per hour for the serving fleet in measurement `m`, under `profile`."""
    n, rps = m["serving_instances"], m["requests_per_second"]
    requests_hour = rps * 3600
    if profile == "as_tested":
        response_bytes = m["measured_response_bytes"]
        reads_hour = n * TESTED_DISTINCT_POINTERS * (3600 / POINTER_CACHE_TTL_SECONDS)   # upper bound
        pointer_items = TESTED_DISTINCT_POINTERS
    else:
        response_bytes = DOC_SIZE_BYTES
        reads_hour = requests_hour                                                        # every request misses
        pointer_items = DOCUMENTS

    compute = n * (R.EC2_T3_MICRO_USD_PER_HOUR + ROOT_VOLUME_GB * R.EBS_GP3_USD_PER_GB_MONTH / HOURS_PER_MONTH)
    ipv4_instances = n * R.PUBLIC_IPV4_IN_USE_USD_PER_HOUR
    ipv4_alb = ALB_PUBLIC_IPV4_ADDRESSES * R.PUBLIC_IPV4_IN_USE_USD_PER_HOUR

    bytes_hour = requests_hour * (m["measured_request_bytes"] + response_bytes)
    lcu = max(m["new_connections_per_second"] / LCU_NEW_CONNECTIONS_PER_SEC,
              m["active_connections_per_minute"] / LCU_ACTIVE_CONNECTIONS_PER_MIN,
              bytes_hour / 1e9 / LCU_PROCESSED_GB_PER_HOUR)
    alb_fixed = R.ALB_USD_PER_HOUR
    alb_lcu = lcu * R.ALB_LCU_USD_PER_LCU_HOUR

    ddb_reads = reads_hour * ddb_read_units(pointer_item_bytes()) * R.DDB_READ_USD_PER_REQUEST_UNIT
    ddb_storage = pointer_storage_month(pointer_items)[0] / HOURS_PER_MONTH
    # Marginal (first-tier) rate: slightly conservative for very large volumes.
    transfer = requests_hour * response_bytes / GIB * R.DATA_TRANSFER_OUT_TIERS_USD_PER_GB[0][2]
    monitoring = (CLOUDWATCH_ALARMS * R.CLOUDWATCH_STANDARD_ALARM_USD_PER_MONTH / HOURS_PER_MONTH
                  if CLOUDWATCH_ALARMS_ARE_BILLED else 0.0)

    parts = {"compute": compute, "public_ipv4": ipv4_instances + ipv4_alb, "alb": alb_fixed + alb_lcu,
             "dynamodb": ddb_reads + ddb_storage, "data_transfer": transfer, "monitoring": monitoring}
    fixed = alb_fixed + ipv4_alb + ddb_storage + monitoring        # does not grow with fleet size
    total = sum(parts.values())
    per_1000 = total / (requests_hour / 1000)
    return dict(
        usd_per_hour=total, components_usd_per_hour=parts,
        components_usd_per_1000_requests={k: v / (requests_hour / 1000) for k, v in parts.items()},
        usd_per_1000_requests=per_1000,
        usd_per_1000_served_requests=per_1000 / m["served_share"],
        # Our k6 load reuses connections, so the new-connection dimension is understated against real
        # browsers. Sensitivity: every request opens a new connection.
        usd_per_1000_requests_if_every_request_is_a_new_connection=per_1000 + (
            max(lcu, rps / LCU_NEW_CONNECTIONS_PER_SEC) - lcu) * R.ALB_LCU_USD_PER_LCU_HOUR / (requests_hour / 1000),
        marginal_usd_per_1000_requests_at_scale=(total - fixed) / (requests_hour / 1000),
        detail=dict(lcu=lcu, lcu_new_connections=m["new_connections_per_second"] / LCU_NEW_CONNECTIONS_PER_SEC,
                    lcu_active_connections=m["active_connections_per_minute"] / LCU_ACTIVE_CONNECTIONS_PER_MIN,
                    lcu_processed_bytes=bytes_hour / 1e9 / LCU_PROCESSED_GB_PER_HOUR,
                    response_bytes=response_bytes, dynamodb_reads_per_hour=reads_hour,
                    requests_per_hour=requests_hour),
    )


def monthly_comparison(baseline, doc_size_bytes=DOC_SIZE_BYTES, attr_bytes=POINTER_ATTR_BYTES, copies=1):
    """USD per month at baseline traffic: Architecture B vs centralised S3. `copies` multiplies stored data."""
    rps = baseline["requests_per_second"]
    requests_month = rps * 3600 * HOURS_PER_MONTH
    n = baseline["serving_instances"]

    fleet = n * (R.EC2_T3_MICRO_USD_PER_HOUR + ROOT_VOLUME_GB * R.EBS_GP3_USD_PER_GB_MONTH / HOURS_PER_MONTH) \
        * HOURS_PER_MONTH
    ipv4 = (n + ALB_PUBLIC_IPV4_ADDRESSES) * R.PUBLIC_IPV4_IN_USE_USD_PER_HOUR * HOURS_PER_MONTH
    bytes_hour = rps * 3600 * (baseline["measured_request_bytes"] + doc_size_bytes)
    lcu = max(baseline["new_connections_per_second"] / LCU_NEW_CONNECTIONS_PER_SEC,
              baseline["active_connections_per_minute"] / LCU_ACTIVE_CONNECTIONS_PER_MIN,
              bytes_hour / 1e9 / LCU_PROCESSED_GB_PER_HOUR)
    alb = (R.ALB_USD_PER_HOUR + lcu * R.ALB_LCU_USD_PER_LCU_HOUR) * HOURS_PER_MONTH
    monitoring = CLOUDWATCH_ALARMS * R.CLOUDWATCH_STANDARD_ALARM_USD_PER_MONTH if CLOUDWATCH_ALARMS_ARE_BILLED else 0.0
    transfer_gib = requests_month * doc_size_bytes / GIB
    transfer = tiered(R.DATA_TRANSFER_OUT_TIERS_USD_PER_GB, transfer_gib)

    ddb_storage, ddb_gib = pointer_storage_month(DOCUMENTS, attr_bytes)
    ddb_storage *= copies
    ddb_reads = requests_month * ddb_read_units(pointer_item_bytes(attr_bytes)) * R.DDB_READ_USD_PER_REQUEST_UNIT

    s3_gib = DOCUMENTS * doc_size_bytes / GIB
    s3_storage = tiered(R.S3_STANDARD_STORAGE_TIERS_USD_PER_GB_MONTH, s3_gib) * copies
    s3_get = requests_month * R.S3_GET_USD_PER_REQUEST

    access_tier = fleet + ipv4 + alb + monitoring
    arch_b = dict(compute=fleet, public_ipv4=ipv4, alb=alb, dynamodb_storage=ddb_storage,
                  dynamodb_reads=ddb_reads, data_transfer=transfer, monitoring=monitoring)
    s3_only = dict(s3_storage=s3_storage, s3_get_requests=s3_get, data_transfer=transfer)
    centralised = dict(access_tier=access_tier, s3_storage=s3_storage, s3_get_requests=s3_get,
                       data_transfer=transfer)
    b_total, s3_total, central_total = sum(arch_b.values()), sum(s3_only.values()), sum(centralised.values())
    return dict(
        requests_per_month=requests_month, documents=DOCUMENTS, doc_size_bytes=doc_size_bytes,
        s3_gib=s3_gib, pointer_table_gib=ddb_gib, copies=copies,
        architecture_b=dict(components_usd_per_month=arch_b, total_usd_per_month=b_total),
        s3_only=dict(components_usd_per_month=s3_only, total_usd_per_month=s3_total),
        centralised_same_access_tier=dict(components_usd_per_month=centralised, total_usd_per_month=central_total),
        gap_s3_only_minus_b=s3_total - b_total, ratio_s3_only_over_b=s3_total / b_total,
        gap_centralised_minus_b=central_total - b_total, ratio_centralised_over_b=central_total / b_total,
        one_off_ingestion=dict(
            s3_put_requests_usd=DOCUMENTS * R.S3_PUT_COPY_POST_LIST_USD_PER_REQUEST,
            dynamodb_pointer_writes_usd=DOCUMENTS * ddb_write_units(pointer_item_bytes(attr_bytes))
            * R.DDB_WRITE_USD_PER_REQUEST_UNIT),
    )


