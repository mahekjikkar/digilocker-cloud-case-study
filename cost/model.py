def utc_minute(stamp):
    return datetime.fromisoformat(stamp).astimezone(timezone.utc).strftime("%H:%M")


def cloudwatch(run, name, stat):
    data = json.loads((run / "cloudwatch" / f"{name}.json").read_text())["Datapoints"]
    return {utc_minute(p["Timestamp"]): p[stat] for p in data}


def measure(name):
    run, raw_name, minutes, expect_healthy, description = WINDOWS[name]
    minutes_set = set(minutes)
    requests_cw = cloudwatch(run, "alb-request-count", "Sum")
    active = cloudwatch(run, "alb-active-connections", "Sum")
    healthy = cloudwatch(run, "tg-healthy-hosts", "Minimum")
    serving = min(healthy[m] for m in minutes)
    assert serving == expect_healthy, f"{name}: expected {expect_healthy} healthy targets, saw {serving}"
    cw_requests = sum(requests_cw[m] for m in minutes)

    served = [0, 0]
    new_connections = 0
    bytes_sent = bytes_received = 0.0
    k6_requests = 0
    wanted = ('"metric":"served"', '"metric":"http_req_connecting"', '"metric":"data_sent"',
              '"metric":"data_received"', '"metric":"http_reqs"')
    with gzip.open(run / raw_name, "rt") as f:
        for line in f:
            if '"type":"Point"' not in line or not any(w in line for w in wanted):
                continue
            point = json.loads(line)
            if utc_minute(point["data"]["time"]) not in minutes_set:
                continue
            metric, value = point["metric"], point["data"]["value"]
            if metric == "served":
                served[0 if value == 1 else 1] += 1
            elif metric == "http_req_connecting":
                new_connections += value > 0
            elif metric == "data_sent":
                bytes_sent += value
            elif metric == "data_received":
                bytes_received += value
            elif metric == "http_reqs":
                k6_requests += value
    seconds = 60 * len(minutes)
    return dict(
        description=description, run=run.name, utc_minutes=minutes,
        serving_instances=int(serving),
        requests_per_second=cw_requests / seconds,
        alb_requests_total=cw_requests, k6_requests_total=k6_requests,
        active_connections_per_minute=sum(active[m] for m in minutes) / len(minutes),
        new_connections_per_second=new_connections / seconds,
        served_share=served[0] / (served[0] + served[1]),
        measured_request_bytes=bytes_sent / k6_requests,
        measured_response_bytes=bytes_received / k6_requests,
    )


