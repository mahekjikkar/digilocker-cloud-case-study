def chart_per_1000(results, path):
    scenarios = [("baseline", "Baseline (E1): {rps:.1f} req/s on {n} instances"),
                 ("peak_burst", "Peak, burst (E2): {rps:.0f} req/s on {n} instances (CPU credits available)"),
                 ("peak_sustained", "Peak, sustained (E2 plateau): {rps:.0f} req/s on {n} instances, "
                                    "{served:.0%} served (credit-limited)")]
    fig, axes = plt.subplots(len(scenarios), 1, figsize=(10.5, 8.2))
    for ax, (key, title) in zip(axes, scenarios):
        m = results["measured"][key]
        labels, rows = [], []
        for profile, name in (("national_scale", "National scale\n(100 KiB docs, cache misses)"),
                              ("as_tested", "As tested\n(mock payload, cached)")):
            labels.append(name)
            rows.append(results["scenarios"][key][profile]["components_usd_per_1000_requests"])
        left = [0.0] * len(rows)
        for comp in COMPONENT_COLORS:
            vals = [r[comp] for r in rows]
            ax.barh(labels, vals, left=left, color=COMPONENT_COLORS[comp], label=COMPONENT_LABELS[comp], height=0.55)
            left = [a + b for a, b in zip(left, vals)]
        for y, total in enumerate(left):
            ax.text(total, y, f"  ${total:.4f}", va="center", fontsize=9)
        ax.set_title(title.format(rps=m["requests_per_second"], n=m["serving_instances"], served=m["served_share"]),
                     fontsize=10, loc="left")
        ax.set_xlim(0, max(left) * 1.22)
        ax.set_xlabel("USD per 1,000 requests", fontsize=9)
        ax.spines[["top", "right"]].set_visible(False)
    handles, names = axes[0].get_legend_handles_labels()
    fig.legend(handles, names, loc="lower center", ncol=3, fontsize=8.5, frameon=False)
    fig.suptitle("Cost per 1,000 requests, Architecture B (ap-south-1, list prices)", fontsize=12, x=0.06, ha="left")
    fig.text(0.06, 0.945, NOTE, fontsize=8.5, color="#B03030", ha="left")
    fig.text(0.94, 0.945, "Each panel has its own scale.", fontsize=8.5, ha="right")
    fig.tight_layout(rect=[0, 0.07, 1, 0.94])
    fig.savefig(path, dpi=160)
    plt.close(fig)


