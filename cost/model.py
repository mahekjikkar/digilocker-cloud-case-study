def main():
    measured = {name: measure(name) for name in WINDOWS}
    scenarios = {name: {p: hourly_cost(m, p) for p in PROFILES} for name, m in measured.items()}
    baseline = measured["baseline"]
    comparison = {"base": monthly_comparison(baseline)}
    comparison["sensitivity_document_size_kib"] = {
        str(kib): {k: v for k, v in monthly_comparison(baseline, doc_size_bytes=kib * 1024).items()
                   if k in ("s3_gib", "gap_s3_only_minus_b", "ratio_s3_only_over_b", "gap_centralised_minus_b")}
        | {"s3_storage_usd_per_month":
           monthly_comparison(baseline, doc_size_bytes=kib * 1024)["s3_only"]["components_usd_per_month"]["s3_storage"]}
        for kib in SENSITIVITY_DOC_SIZES_KIB}
